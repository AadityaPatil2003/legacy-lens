"""Generate a Markdown comprehension document from an analysis."""

from __future__ import annotations

from legacylens.flows import to_mermaid
from legacylens.models import Analysis, ProgramSummary
from legacylens.parsers.copybook import flatten


def _table(headers: list[str], rows: list[list[object]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join("" if v is None else str(v) for v in row) + " |")
    return "\n".join(out)


def render_report(analysis: Analysis, summaries: list[ProgramSummary] | None = None) -> str:
    summaries_by_id = {s.program_id: s for s in summaries or []}
    parts = ["# LegacyLens comprehension report", ""]
    parts.append(
        _table(
            ["Artefact", "Count"],
            [
                ["COBOL programs", len(analysis.programs)],
                ["Copybooks", len(analysis.copybooks)],
                ["BMS maps", len(analysis.screens)],
                ["IMS MFS formats", len(analysis.mfs_formats)],
                ["JCL jobs", len(analysis.jobs)],
            ],
        )
    )

    for program in analysis.programs:
        parts += ["", f"## Program {program.program_id} ({program.program_type})", ""]
        summary = summaries_by_id.get(program.program_id)
        if summary:
            parts += [f"**Purpose.** {summary.purpose}", "", "**Business rules**", ""]
            parts += [f"- {rule}" for rule in summary.business_rules]
            parts += ["", "**Inputs:** " + (", ".join(summary.inputs) or "none detected")]
            parts += ["", "**Outputs:** " + (", ".join(summary.outputs) or "none detected")]
            parts += ["", "**Modernisation notes**", ""]
            parts += [f"- {note}" for note in summary.modernisation_notes]
            parts += ["", f"_Summary generated by {summary.generated_by}._"]
        parts += ["", "**Paragraph call tree**", ""]
        parts += [
            f"- `{p.name}`"
            + (f" → performs {', '.join(f'`{t}`' for t in p.performs)}" if p.performs else "")
            + (f"; calls {', '.join(p.calls)}" if p.calls else "")
            for p in program.paragraphs
        ]
        if program.cics_commands:
            parts += ["", "**CICS commands**", ""]
            parts.append(
                _table(
                    ["Paragraph", "Command", "Options"],
                    [
                        [c.paragraph, c.command, ", ".join(f"{k}={v}" if v else k for k, v in c.options.items())]
                        for c in program.cics_commands
                    ],
                )
            )

    for screen in analysis.screens + [m.screen for m in analysis.mfs_formats]:
        parts += ["", f"## Screen {screen.mapset}.{screen.map_name} ({screen.source.upper()})", ""]
        parts.append(
            _table(
                ["Field", "Row", "Col", "Len", "Input", "Attributes / text"],
                [
                    [
                        f.name or "(label)",
                        f.row,
                        f.column,
                        f.length,
                        "yes" if f.input else "",
                        f.initial or ", ".join(f.attributes),
                    ]
                    for f in screen.fields
                ],
            )
        )

    for copybook in analysis.copybooks:
        parts += ["", f"## Copybook {copybook.name} (record length {copybook.record_length} bytes)", ""]
        parts.append(
            _table(
                ["Field", "PIC", "Usage", "Offset", "Length", "Occurs", "Redefines"],
                [
                    [
                        r["path"].split(".")[-1],
                        r["picture"],
                        r["usage"],
                        r["offset"],
                        r["length"],
                        r["occurs"],
                        r["redefines"],
                    ]
                    for r in flatten(copybook.fields)
                ],
            )
        )

    for job in analysis.jobs:
        parts += ["", f"## Job {job.job_name}" + (f" – {job.description}" if job.description else ""), ""]
        parts.append(
            _table(
                ["Step", "Program", "From PROC", "COND", "Datasets"],
                [
                    [
                        s.step_name,
                        s.program or s.proc,
                        s.expanded_from_proc,
                        s.condition,
                        "<br>".join(f"{d.ddname}: {d.dsn} ({d.disp})" for d in s.dd_statements if d.dsn),
                    ]
                    for s in job.steps
                ],
            )
        )

    if analysis.flows:
        parts += ["", "## Transaction flows"]
        for flow in analysis.flows:
            parts += ["", f"### {flow.name}", "", "```mermaid", to_mermaid(flow), "```"]

    if analysis.warnings:
        parts += ["", "## Warnings", ""] + [f"- {w}" for w in analysis.warnings]
    return "\n".join(parts) + "\n"
